class StageService:
    """关卡生成服务门面。"""

    def list_tasks(self) -> list[dict[str, Any]]:
        """列出全部可用任务。

        入参：无。
        出参：任务摘要列表，含 key、stage、index、title、question。
        失败行为：不抛异常。
        """
        return [                                  # 直接从任务规格派生，避免两处维护
            {
                "key": key,                       # 任务键，如 opportunity:1
                "stage": spec["stage"],           # 所属阶段
                "index": spec["index"],           # 阶段内序号
                "title": spec["title"],           # 任务标题
                "question": spec["question"],     # 平台原问题
            }
            for key, spec in prompts.TASK_SPECS.items()   # 遍历六个任务
        ]

    def _build(self, task_key: str, extra_question: str) -> tuple[str, str]:
        """调用本地模型生成。

        入参：task_key 任务键；extra_question 追加要求。
        出参：二元组 (正文, 生成来源)，来源为 "ollama"。
        失败行为：模型不可用或生成失败抛 RuntimeError，由 generate 捕获降级。
        """
        evidence = kg.evidence_index()                                        # 取全量证据，作为唯一事实来源
        user_prompt = prompts.build_user_prompt(task_key, evidence, extra_question)   # 组装用户提示词
        content = ollama.generate(prompts.SYSTEM_PROMPT, user_prompt)          # 调本地模型
        return content, "ollama"                                              # 标明来源，便于排查

    def generate(self, task_key: str, extra_question: str = "", force_template: bool = False) -> dict[str, Any]:
        """生成指定关卡任务的答卷，并强制通过 Harness。

        入参：
            task_key: 任务键，如 "opportunity:1"。
            extra_question: 追加要求，可为空。
            force_template: 强制走模板引擎，便于离线或对照测试。
        出参：
            字典：taskKey、title、content、source、harness（校验报告）。
        失败行为：
            task_key 不存在抛 NotFoundError；模型失败时自动降级，不向调用方抛异常。
        """
        if task_key not in prompts.TASK_SPECS:   # 任务键白名单校验，防止任意字符串进来
            raise NotFoundError(f"任务不存在：{task_key}，可选：{list(prompts.TASK_SPECS)}")

        spec = prompts.TASK_SPECS[task_key]   # 取任务规格用于回填标题与原问题
        source = "template"                   # 默认来源是模板，后续可能被模型覆盖
        content = FALLBACK[task_key]          # 默认正文是兜底模板

        if not force_template and ollama.is_available():   # 未强制模板且模型就绪才尝试模型路径
            try:
                raw, source = self._build(task_key, extra_question)   # 调模型生成
                # 模型输出必须先过 Harness：未通过就丢弃，改用模板，绝不带病返回
                report = run_checks(raw)                              # 在返回前校验，而不是事后人工检查
                if report["passed"]:                                  # 只有合规输出才允许直接返回
                    content = raw                                     # 采用模型正文
                else:                                                 # 不合规则整体丢弃
                    logger.warning("模型输出未通过 Harness（%d 分），降级为模板引擎", report["score"])
                    source = "template(harness-fallback)"             # 明确标记「模型输了但被拦回」
            except RuntimeError as exc:                               # 模型不可用 / 超时 / 空返回
                logger.warning("模型生成失败，降级为模板引擎：%s", exc)
                source = "template"                                   # 回落模板，服务保持可用

        report = run_checks(content)   # 对最终返回的正文再校验一次，保证报告与正文一致
        return {                                                                     # 统一返回结构
            "taskKey": task_key,                          # 任务键
            "title": spec["title"],                       # 任务标题
            "question": spec["question"],                 # 平台原问题
            "content": content,                           # 最终正文（模型输出或模板）
            "source": source,                             # 来源，便于区分模型输出与兜底
            "length": len(content),                       # 字数，便于快速判断是否被截断
            "harness": report,                            # 完整校验报告
        }


