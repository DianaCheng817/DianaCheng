def build_evidence_block(evidence: dict[str, str], limit: int = 40) -> str:
    """把证据编号与正文拼成 <evidence> 区块。

    入参：
        evidence: 证据编号 -> 事实正文 的字典。
        limit: 最多注入的条数，避免提示词过长。
    出参：可直接放入用户提示词的字符串。
    失败行为：evidence 为空时返回提示性说明，不抛异常。
    """
    if not evidence:   # 空库时给出明确提示，避免模型凭空编造
        return "<evidence>\n（知识库为空，请先载入访谈事实）\n</evidence>"

    lines = ["<evidence>"]                                              # 开标签
    for idx, (key, text) in enumerate(sorted(evidence.items())):       # 按编号排序，保证同样输入同样提示词
        if idx >= limit:                                               # 超过条数上限
            break                                                      # 提前结束，控制提示词长度
        lines.append(f"{key}｜{text}")                                  # 一行一条事实
    lines.append("</evidence>")                                        # 闭标签
    return "\n".join(lines)                                            # 拼成多行文本


def build_user_prompt(task_key: str, evidence: dict[str, str], extra_question: str = "") -> str:
    """组装用户提示词。

    入参：
        task_key: 关卡任务键，如 "opportunity:1"。
        evidence: 证据字典。
        extra_question: 用户追加的具体问题，可为空。
    出参：完整用户提示词字符串。
    失败行为：task_key 不存在时抛 KeyError，由上层转换为业务异常。
    """
    spec = TASK_SPECS[task_key]                                        # 取任务规格，键不存在会 KeyError
    parts = [                                                          # 五段式：任务、原问题、证据、骨架、输出要求
        f"【任务】{spec['title']}",                                     # 任务标题
        f"【平台原问题】{spec['question']}",                            # 平台原问题，保证答的是题面
        build_evidence_block(evidence),                                # 证据区块，唯一的可引用事实
        f"【写作骨架】\n{spec['instruction']}",                          # 写作骨架
        "【输出要求】只输出正文，不要加前言、不要复述提示词、不要输出代码。"
        "正文结构固定为：我的理解与结论 → 判断依据 → 待核实的事项。",   # 输出纪律，压制模型的闲聊倾向
    ]
    if extra_question.strip():                                         # 有追加要求才追加
        parts.append(f"【追加要求】{extra_question.strip()}")           # 去掉首尾空白后原样带入
    return "\n\n".join(parts)                                          # 段间空行，便于模型分块理解
